// SEATS (Shuttle 01 – 30 seats)
// ============================================================
function buildSeats(): Seat[] {
  const seats: Seat[] = [];
  const occupiedSeats = mockStudents.filter(
    (s) => s.currentShuttle === 'VIT-SHUTTLE-01' && s.currentSeat !== null
  );

  for (let i = 1; i <= 30; i++) {
    const occupant = occupiedSeats.find((s) => s.currentSeat === i);
    if (occupant) {
      seats.push({
        id: `seat-${i}`,
        number: i,
        status: 'OCCUPIED',
        studentId: occupant.registerNumber,
        studentName: occupant.name,
        gender: occupant.gender,
        temperature: +(36.1 + Math.random() * 1.1).toFixed(1),
        pressure: 'HIGH',
        entryTime: '09:10',
        tripId: occupant.tripId,
      });
    } else if (i === 8 || i === 24) {
      seats.push({
        id: `seat-${i}`,
        number: i,
        status: 'OBJECT',
        studentId: null,
        studentName: null,
        gender: null,
        temperature: +(25.0 + Math.random() * 5).toFixed(1),
        pressure: 'HIGH',
        entryTime: null,
        tripId: null,
      });
    } else {
      seats.push({
        id: `seat-${i}`,
        number: i,
        status: 'AVAILABLE',
        studentId: null,
        studentName: null,
        gender: null,
        temperature: null,
        pressure: null,
        entryTime: null,
        tripId: null,
      });
    }
  }
  return seats;
}

